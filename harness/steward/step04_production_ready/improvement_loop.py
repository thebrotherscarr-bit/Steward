def _ollama_base_url() -> str:
    """OLLAMA_HOST as Ollama reads it: a bare host such as 127.0.0.1 means http://127.0.0.1:11434."""
    host = os.environ.get("OLLAMA_HOST", "").strip().rstrip("/") or "127.0.0.1"
    if "://" not in host:
        host = f"http://{host}"
    scheme, _, rest = host.partition("://")
    if ":" not in rest.split("/", 1)[0]:
        rest = rest.replace("/", ":11434/", 1) if "/" in rest else f"{rest}:11434"
    return f"{scheme}://{rest}"


