def format_duration(seconds: float) -> str:
    minutes, remainder = divmod(int(round(seconds)), 60)
    return f"{minutes}m {remainder:02d}s" if minutes else f"{remainder}s"


async def structured(prompt: str, model: str, response_format: type[Any]) -> Any:
    """One model call whose reply is parsed into ``response_format``: MAF's structured output (ADR
    0036), where the notebook asks for JSON in the prompt and parses the text with extract_json."""
    from agent_framework import Message
    from agent_framework.ollama import OllamaChatClient

    response = await OllamaChatClient(model=model).get_response(
        [Message(role="user", contents=[prompt])],
        options={"response_format": response_format, "think": MODEL_SETTINGS["reasoning_effort"]},
    )
    return response.value


