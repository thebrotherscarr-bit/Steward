@dataclass
class TraceRecord:
    trace_id: str
    trace_label: str
    question: str
    answer: str
    mode: str


async def generate_traces(questions: list[str]) -> tuple[list[TraceRecord], dict[str, Any], list[Any]]:
    """Each ask once through evals.run_small_asks (the runner evals.py small uses: his workflow through run_steward,
    the same approvals, the discount bug planted for the discount ask, the sample project put back, a throwaway memory
    per run), each in its own trace span. Also returns the small-ask checks' scored items, one per ask."""
    from contextlib import contextmanager

    sys.path.insert(0, str(_SELF.parent))
    import evals  # noqa: PLC0415
    from agent_framework.observability import get_tracer
    from halo_traces import setup_halo_tracing  # noqa: PLC0415
    from opentelemetry.trace.span import format_trace_id

    setup_halo_tracing(HALO_TRACE_PATH)
    opened: list[tuple[str, str]] = []

    @contextmanager
    def traced(question: str) -> Any:
        label = f"trace-{len(opened) + 1:02d}"
        print(f"Running {label}/{len(questions):02d}: {question}")
        with get_tracer().start_as_current_span(f"Steward improvement loop {label}") as span:
            opened.append((format_trace_id(span.get_span_context().trace_id), label))
            yield

    steward, responses = await evals.run_small_asks(questions, around=traced)
    traces = [
        TraceRecord(trace_id, label, question, response.text, mode="workflow")
        for (trace_id, label), question, response in zip(opened, questions, responses, strict=True)
    ]
    checks = await evals.score_small_asks(steward, questions, responses)
    return traces, serialize_agent_config(steward), list(checks.items)


def serialize_agent_config(steward: Any) -> dict[str, Any]:
    """The harness that ran, for HALO's config span: his workflow's steps and the agent its steps run (its first
    AgentExecutor's; the start step is the router), with its instructions, model, tools and providers, and the
    approvals the runs were given."""
    from agent_framework import AgentExecutor

    workflow = steward.workflow
    agent = next(e.agent for e in workflow.get_executors_list() if isinstance(e, AgentExecutor))
    revision = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=_REPO_DIR, capture_output=True, text=True)
    tools = [getattr(t, "name", type(t).__name__) for t in (agent.default_options or {}).get("tools", [])]
    return {
        "version": revision.stdout.strip() or "unknown",
        "system_prompt": agent.default_options.get("instructions") or "",
        # His own model and options, as the Agent tab runs him; the effort is the loop's analysis, judge and HALO.
        "model_settings": {
            "agent_model": getattr(getattr(agent, "client", None), "model", None) or MODEL_SETTINGS["agent_model"],
            "analysis_reasoning_effort": MODEL_SETTINGS["reasoning_effort"],
        },
        "tool_policy": {
            "workflow": getattr(workflow, "name", None) or "steward",
            "workflow_steps": list(workflow.executors),
            "tools": tools,
            "context_providers": [type(p).__name__ for p in agent.context_providers],
            "approvals": "the plan card and file writes approved, every other card denied (as in evals.py small)",
            "skill_scripts": "auto-approved for this loop (as in evals.py small)",
        },
        "eval_metadata": {
            "source": "steward_workflow.build_steward through evals.run_steward",
            "evals": "evals.py small and this loop",
        },
    }


