async def run_halo_optimization(context_path: Path) -> str:
    """The notebook's HALO pass, in .venv-halo, against local Ollama."""
    from agents import set_trace_processors
    from engine.agents.agent_config import AgentConfig as HaloAgentConfig
    from engine.engine_config import EngineConfig
    from engine.main import stream_engine_async
    from engine.model_config import ModelConfig
    from engine.model_provider_config import ModelProviderConfig
    from engine.models.engine_output import AgentOutputItem, AgentTextDelta
    from engine.models.messages import AgentMessage
    from engine.sandbox.sandbox import Sandbox

    effort = MODEL_SETTINGS["reasoning_effort"]
    agent = HaloAgentConfig(name="root", model=ModelConfig(name=HALO_MODEL, reasoning_effort=effort), maximum_turns=20)
    config = EngineConfig(
        root_agent=agent,
        subagent=agent.model_copy(update={"name": "sub"}),
        synthesis_model=ModelConfig(name=HALO_MODEL, reasoning_effort=effort),
        compaction_model=ModelConfig(name=HALO_MODEL, temperature=1.0, reasoning_effort=effort),
        model_provider=ModelProviderConfig(base_url=OLLAMA_V1, api_key="ollama"),
        maximum_depth=1,
        maximum_parallel_subagents=2,
    )

    # As in the notebook: no hosted trace ingestion for this pass, and no `run_code` sandbox (its
    # Pyodide download is skipped).
    set_trace_processors([])

    deltas: list[str] = []
    final_items: list[str] = []
    messages = [AgentMessage(role="user", content=render_halo_prompt())]

    async def report_progress(done: asyncio.Event, interval_seconds: int = 30) -> None:
        started = time.perf_counter()
        print("HALO optimization started. This is usually the longest step.", flush=True)
        while not done.is_set():
            try:
                await asyncio.wait_for(done.wait(), timeout=interval_seconds)
            except TimeoutError:
                print(f"HALO still running... {format_duration(time.perf_counter() - started)} elapsed", flush=True)

    original_sandbox_get = Sandbox.__dict__["get"]
    Sandbox.get = classmethod(lambda cls: None)
    halo_started = time.perf_counter()
    progress_done = asyncio.Event()
    progress_task = asyncio.create_task(report_progress(progress_done))
    try:
        async for event in stream_engine_async(messages, config, context_path):
            if isinstance(event, AgentTextDelta):
                deltas.append(event.text_delta)
            elif isinstance(event, AgentOutputItem) and event.final:
                final_items.append(str(event.item.content or ""))
    finally:
        progress_done.set()
        await progress_task
        Sandbox.get = original_sandbox_get

    print(f"HALO optimization completed in {format_duration(time.perf_counter() - halo_started)}")
    # HALO's final=True item carries the answer as plain text (engine/agents/openai_event_mapper.py);
    # on Ollama the streamed deltas are the raw `final_answer` call arguments, so the item comes first.
    report = "\n\n".join(final_items).strip() or "".join(deltas).strip()
    if not report:
        raise RuntimeError("HALO completed without producing a report.")
    return report


def clean_halo_handoff(report: str) -> str:
    """Keep only the final handoff sections from HALO output."""
    normalized = re.sub(r"(?<!\n)(## Executive summary)", r"\n\n\1", report).strip()
    start = normalized.rfind("## Executive summary")
    if start == -1:
        raise ValueError("HALO output did not include the expected executive summary section.")
    handoff = normalized[start:].strip()
    required_headings = [
        "## Executive summary",
        "## Top 3 changes to implement first",
        "## Ranked recommendation table",
        "## Supporting diagnosis and evidence",
        "## Detailed recommendations",
        "## Insights by feedback source",
        "## Machine-readable summary",
    ]
    missing = [heading for heading in required_headings if heading not in handoff]
    if missing:
        raise ValueError(f"HALO handoff is missing required sections: {missing}")
    return handoff


def read_handoff(path: Path = HANDOFF_PATH) -> str:
    """The handoff's text. A report HALO returned as its final_answer call's JSON string (literal \\n, a closing
    quote and brace, as some Ollama runs saved it) is decoded first."""
    text = path.read_text(encoding="utf-8").strip()
    if text.count("\\n") > text.count("\n") and '"' in text:
        text = json.loads('"' + text.rsplit('"', 1)[0] + '"').strip()
    return text


def handoff_priorities(text: str) -> list[str]:
    """The handoff's `top_priorities`, in order, each as one line: a plain string, or an object's
    recommendation, description, title or id (HALO writes all of these shapes)."""
    _, found, summary = text.partition("## Machine-readable summary")
    match = re.search(r"```json\s*(.*?)```", summary, re.S)
    if not found or match is None:
        raise ValueError("The handoff has no machine-readable summary with a JSON block.")
    lines = []
    for item in json.loads(match.group(1)).get("top_priorities") or []:
        if isinstance(item, dict):
            item = next((item[k] for k in ("recommendation", "description", "title", "id") if item.get(k)), "")
        if isinstance(item, str) and item.strip():
            lines.append(item.strip())
    if not lines:
        raise ValueError("The handoff's machine-readable summary lists no top_priorities.")
    return lines


def handoff_task(path: Path = HANDOFF_PATH) -> str:
    """One improvement round's task from the diagnosis: the handoff's first top priority, with the whole handoff
    as its evidence, as the notebook gives Codex codex_handoff.md."""
    if not path.exists():
        raise FileNotFoundError(f"No diagnosis handoff at {path}: run improvement_loop.py first, or name the failure.")
    text = read_handoff(path)
    first = handoff_priorities(text)[0]
    shown = path.relative_to(_REPO_DIR) if path.is_relative_to(_REPO_DIR) else path
    return (
        f"{first}\n\nThis is the first of the top priorities in the diagnosis's handoff ({shown.as_posix()}). "
        f"Do only this one. The handoff, in full:\n\n{text}"
    )


def halo_main(context_path: Path, report_path: Path) -> None:
    """``improvement_loop.py halo <context> <report>``: run under .venv-halo."""
    report = asyncio.run(run_halo_optimization(context_path))
    report_path.write_text(report + "\n", encoding="utf-8")


