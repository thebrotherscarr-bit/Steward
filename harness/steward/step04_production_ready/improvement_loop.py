@dataclass
class TraceRecord:
    trace_id: str
    trace_label: str
    question: str
    answer: str
    mode: str


async def generate_traces(questions: list[str]) -> tuple[list[TraceRecord], dict[str, Any]]:
    from contextlib import AsyncExitStack

    sys.path.insert(0, str(_SELF.parent))
    from agent import build_steward_agent  # noqa: PLC0415
    from agent_framework.observability import get_tracer
    from halo_traces import setup_halo_tracing  # noqa: PLC0415
    from opentelemetry.trace.span import format_trace_id

    setup_halo_tracing(HALO_TRACE_PATH)
    traces: list[TraceRecord] = []
    async with AsyncExitStack() as stack:
        agent = await build_steward_agent(stack, enable_shell=False, auto_approve_skill_scripts=True)
        async with agent:
            harness = serialize_agent_config(agent)
            for index, question in enumerate(questions, start=1):
                label = f"trace-{index:02d}"
                print(f"Running {label}/{len(questions):02d}: {question}")
                with get_tracer().start_as_current_span(f"Steward improvement loop {label}") as span:
                    trace_id = format_trace_id(span.get_span_context().trace_id)
                    response = await agent.run(question, session=agent.create_session())
                traces.append(TraceRecord(trace_id, label, question, response.text, mode="maf"))
    return traces, harness


def serialize_agent_config(agent: Any) -> dict[str, Any]:
    """The current harness, for HALO's config span: instructions, model, tools and providers."""
    revision = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=_REPO_DIR, capture_output=True, text=True)
    tools = [getattr(t, "name", type(t).__name__) for t in (agent.default_options or {}).get("tools", [])]
    return {
        "version": revision.stdout.strip() or "unknown",
        "system_prompt": agent.default_options.get("instructions") or "",
        "model_settings": {"agent_model": AGENT_MODEL},
        "tool_policy": {
            "tools": tools,
            "context_providers": [type(p).__name__ for p in agent.context_providers],
            "shell": "off for this loop (as in evals.py)",
            "skill_scripts": "auto-approved for this loop (as in evals.py)",
        },
        "eval_metadata": {"source": "build_steward_agent part 4", "evals": "evals.py and this loop"},
    }


