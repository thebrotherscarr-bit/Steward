# Step 4. Human feedback and model insights. The human feedback is the operator's, kept in diagnosis_feedback.json
# (a list keyed by the ask; edit the file, not this code); the small-ask checks' failing verdicts on each traced run
# are feedback too (source_type eval_checks); the insights come from a model reading the traces.
FEEDBACK_PATH = _SELF.with_name("diagnosis_feedback.json")


def feedback_item(
    trace: TraceRecord, summary: str, required: list[str], prohibited: list[str], theme: str,
    source_type: str = "human_feedback", feedback_id: str | None = None,
) -> dict[str, Any]:
    return {
        "feedback_id": feedback_id or f"human-{trace.trace_label}",
        "trace_id": trace.trace_id,
        "trace_label": trace.trace_label,
        "question": trace.question,
        "source_type": source_type,
        "theme": theme,
        "summary": summary,
        "required_observations": required,
        "prohibited_claims": prohibited,
    }


def generate_human_feedback(traces: list[TraceRecord], path: Path = FEEDBACK_PATH) -> list[dict[str, Any]]:
    """The feedback file's entry for each traced ask; an ask with no entry gets none."""
    entries = {entry["ask"]: entry for entry in json.loads(path.read_text(encoding="utf-8"))}
    return [
        feedback_item(
            trace, entry["summary"], list(entry["required_observations"]), list(entry["prohibited_claims"]), entry["theme"]
        )
        for trace in traces
        if (entry := entries.get(trace.question)) is not None
    ]


def eval_check_feedback(traces: list[TraceRecord], items: list[Any]) -> list[dict[str, Any]]:
    """One feedback item per failing small-ask check on a traced run (evals.score_small_asks' items, one per trace),
    with the check's reason, so the diagnosis sees the deterministic checks beside the human feedback."""
    found = []
    for trace, item in zip(traces, items, strict=True):
        for score in item.scores:
            if score.passed is not False:
                continue
            reason = str((score.sample or {}).get("reason", ""))
            found.append(feedback_item(
                trace, f"The {score.name} check failed: {reason}", [f"Passes the {score.name} check"], [], score.name,
                source_type="eval_checks", feedback_id=f"eval-{trace.trace_label}-{score.name}",
            ))
    return found


class LlmInsight(BaseModel):
    insight_id: str
    trace_id: str
    question: str
    source_type: str
    observations: list[str]


class LlmInsights(BaseModel):
    insights: list[LlmInsight]


async def generate_llm_feedback(traces: list[TraceRecord]) -> list[dict[str, Any]]:
    payload = [asdict(trace) for trace in traces]
    result = await structured(
        f"""
You are reviewing traces from Steward, a software engineering assistant agent.
Return a list of objects with keys `insight_id`, `trace_id`, `question`, `source_type`, and `observations`.
Use `source_type` = `llm_insight`.
For `trace_id`, copy the provided `trace_id` field exactly; do not use `trace_label`.
For each trace, identify concise recurring-behavior observations that could help generate evals later.
Do not restate the whole answer. Do not invent unavailable evidence.

Traces:
{json.dumps(payload, indent=2)}
""".strip(),
        ANALYSIS_MODEL,
        LlmInsights,
    )
    parsed = [item.model_dump() for item in result.insights]
    trace_labels = {trace.trace_id: trace.trace_label for trace in traces}
    for item in parsed:
        try:
            item["trace_label"] = trace_labels[item["trace_id"]]
        except KeyError as exc:
            raise ValueError(f"Unknown trace_id in LLM feedback: {item['trace_id']}") from exc
    return parsed


