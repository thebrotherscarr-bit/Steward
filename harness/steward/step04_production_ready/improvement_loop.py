class LlmInsight(BaseModel):
    insight_id: str
    trace_id: str
    question: str
    source_type: str
    observations: list[str]


class LlmInsights(BaseModel):
    insights: list[LlmInsight]


async def generate_llm_feedback(traces: list[TraceRecord]) -> list[dict[str, Any]]:
    payload = [asdict(trace) for trace in traces]
    result = await structured(
        f"""
You are reviewing traces from Steward, a software engineering assistant agent.
Return a list of objects with keys `insight_id`, `trace_id`, `question`, `source_type`, and `observations`.
Use `source_type` = `llm_insight`.
For `trace_id`, copy the provided `trace_id` field exactly; do not use `trace_label`.
For each trace, identify concise recurring-behavior observations that could help generate evals later.
Do not restate the whole answer. Do not invent unavailable evidence.

Traces:
{json.dumps(payload, indent=2)}
""".strip(),
        ANALYSIS_MODEL,
        LlmInsights,
    )
    parsed = [item.model_dump() for item in result.insights]
    trace_labels = {trace.trace_id: trace.trace_label for trace in traces}
    for item in parsed:
        try:
            item["trace_label"] = trace_labels[item["trace_id"]]
        except KeyError as exc:
            raise ValueError(f"Unknown trace_id in LLM feedback: {item['trace_id']}") from exc
    return parsed


